//write a program to demonstrate the use of relational operators
#include <stdio.h>
int main(){
    int a,h;
    printf("Enter the value of a");
    scanf("%d",&a);
    printf("Enter the value of h");
    scanf("%d",&h);
    printf("a==h:%d\n", a==h);
    printf("a!=h:%d\n", a!=h);
    printf("a>h:%d\n", a>h);
    printf("a<h:%d\n", a<h);
    printf("a>=h:%d\n", a>=h);
    printf("a<=h:%d\n", a<=h);
    return 0;
}