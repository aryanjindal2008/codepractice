#include <stdio.h>
int main(){
    int a,h;
    printf("enter value of a:");
    scanf("%d",&a);
    printf("enter value of h:");
    scanf("%d",&h);
    printf("a + h = %d\n", a + h);
    printf("a - h = %d\n", a - h);
    printf("a * h = %d\n", a * h);
    printf("a / h = %d\n", a / h);

    return 0;}
